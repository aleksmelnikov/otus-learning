#pragma once

#include <cstddef>

// Вспомогательный тип для проверки вызова деструкторов.
//
// У объектов есть единственное состояние — общий счётчик
// живых экземпляров. Это позволяет тесту destruction заметить, что при
// уничтожении контейнера деструктор был вызван для каждого элемента.
class TrackedType {
public:
    // Конструктор по умолчанию: создаёт новый объект и увеличивает счётчик.
    TrackedType() {
        ++counter();
    }

    // Копирующий конструктор: создаёт копию объекта и увеличивает счётчик.
    TrackedType(const TrackedType&) {
        ++counter();
    }

    // Перемещающий конструктор: создаёт новый объект, а старый продолжает
    // существовать до своего уничтожения. Поэтому также увеличивает счётчик.
    TrackedType(TrackedType&&) noexcept {
        ++counter();
    }

    // Копирующее присваивание: не создаёт новый объект и не уничтожает
    // старый, поэтому счётчик живых экземпляров менять не нужно.
    TrackedType& operator=(const TrackedType&) = default;

    // Перемещающее присваивание: по той же причине счётчик не меняется.
    TrackedType& operator=(TrackedType&&) noexcept = default;

    // Деструктор: уничтожает объект и уменьшает общий счётчик.
    ~TrackedType() {
        --counter();
    }

    // Геттер счётчика: тест сравнивает значение до создания
    // контейнера, во время его жизни и после уничтожения.
    static std::size_t aliveCount() {
        return counter();
    }

private:
    // Возвращает ссылку на единственный счётчик. Локальная статическая
    // переменная создаётся при первом вызове и существует до конца программы.
    static std::size_t& counter() {
        static std::size_t value = 0;
        return value;
    }
};
